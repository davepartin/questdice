#!/usr/bin/env node
// Generate docs/MINIS.md from minis/catalog.json so the human page cannot drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.join(root, 'minis/catalog.json');
const outPath = path.join(root, 'docs/MINIS.md');

export function loadCatalog() {
  return JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
}

export function renderMinisMd(cat) {
  const minis = cat.minis || [];
  const monsters = minis.filter((m) => m.kind === 'monster');
  const heroes = minis.filter((m) => m.kind === 'hero');
  const fam = (list) => {
    const g = {};
    for (const m of list) (g[m.family] ||= []).push(m);
    return g;
  };
  const nameLine = (m) => {
    const names = (m.names || []).map((n) => {
      const packs = n.packs?.length ? ` (${n.packs.join(', ')})` : '';
      return `${n.name}${packs}`;
    });
    return names.join(' · ') || m.title;
  };
  const campaigns = (m) => (m.campaigns || []).join(', ') || '—';
  const block = (m) => {
    const reskin = (m.reskinAs || []).map((s) => `\`${s}\``).join(', ');
    const lines = [
      `### \`${m.id}\` — ${m.title}`,
      '',
      `- **Image:** \`${m.image}\``,
      `- **In-game name(s):** ${nameLine(m)}`,
      `- **Family / tone / size / role:** ${m.family} · ${m.tone} · ${m.size} · ${m.role}`,
      `- **Stats template:** \`${m.statsFrom}\``,
      `- **Campaigns:** ${campaigns(m)}`,
      `- **Reskin as:** ${reskin || '—'}`,
      '',
      m.description,
      '',
    ];
    return lines.join('\n');
  };
  const byFam = (list) => {
    const g = fam(list);
    const order = ['beast', 'folk', 'giant', 'undead', 'shadow', 'construct', 'dragon', 'elemental', 'plant', 'otherworldly', 'hero'];
    const keys = [...order.filter((k) => g[k]), ...Object.keys(g).filter((k) => !order.includes(k)).sort()];
    return keys.map((k) => `## ${k[0].toUpperCase()}${k.slice(1)}\n\n${g[k].map(block).join('\n')}`).join('\n');
  };

  const guide = cat.writerGuide || '';
  return [
    '# QuestDice miniature catalog',
    '',
    'Machine-readable source: `minis/catalog.json`. Rebuild this page with `node tools/minis-md.mjs`. Do not edit this file by hand.',
    '',
    guide.trim(),
    '',
    `**${monsters.length} monsters** and **${heroes.length} hero looks**. Cast by \`id\`. Rename freely. Do not invent art.`,
    '',
    '## Heroes',
    '',
    heroes.map(block).join('\n'),
    byFam(monsters),
  ].join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const cat = loadCatalog();
  const md = renderMinisMd(cat);
  if (process.argv.includes('--check')) process.stdout.write(md);
  else {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, md);
    console.log(`wrote ${path.relative(root, outPath)} (${cat.minis.length} minis)`);
  }
}
